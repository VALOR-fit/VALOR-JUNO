#ifndef JUNO_DETECTOR_RESPONSE_H
#define JUNO_DETECTOR_RESPONSE_H

#include <array>
#include <map>
#include <string>
#include <utility>
#include <vector>

class TH2D;

namespace juno {

/// Lightweight JUNO detector response helper for VALOR-JUNO.
///
/// Intended use:
///   1. Fill one or more fine true-space TH2D spectra after oscillation/systematics.
///   2. Call Apply(...) to produce coarse reco-space spectra.
///
/// Response order:
///   true oscillated spectrum -> FC ratio -> E smearing -> cos(theta) smearing -> PID.
///
/// PID convention:
///   labels: 0=nue, 1=numu, 2=nuebar, 3=numubar, 4=nc
///   matrix storage is PID[true][reco], i.e. rows are true labels and columns are reco labels.
///   The output sample mapping is:
///     reco nue    -> sample 52
///     reco numu   -> sample 50
///     reco nuebar -> sample 53
///     reco numubar-> sample 51
///     reco nc is ignored by default because the current 4CC sample setup has no NC sample.
class JunoDetectorResponse {
public:
  enum class Flavor {
    kNuE,
    kNuMu,
    kNuEBar,
    kNuMuBar,
    kNC
  };

  struct Config {
    bool apply_fc = false;
    bool apply_energy_smearing = false;
    bool apply_costh_smearing = false;
    bool apply_pid = false;
    bool preserve_normalization = false;
    double smear_nsigma = 5.0;
  };

  struct Component {
    int input_sample = 0;   ///< Sample used if PID is disabled.
    int reac_mode = 0;      ///< VALOR reaction mode label to preserve in output map.
    Flavor final_flavor = Flavor::kNC;
    const TH2D* true_spectrum = nullptr; ///< Fine true E vs true cos(theta) spectrum.
  };

  using HistKey = std::pair<int, int>; ///< (sample, reac_mode)
  using HistMap = std::map<HistKey, TH2D*>;

  JunoDetectorResponse();
  ~JunoDetectorResponse();

  void SetConfig(const Config& cfg);
  const Config& GetConfig() const;

  void SetAnalysisBinning(const std::vector<double>& e_edges,
                          const std::vector<double>& costh_edges);

  /// Load FC polynomial coefficients from the same text format generated by the shell script:
  ///   numu=a,b,c
  ///   nue=a,b,c
  ///   numubar=a,b,c
  ///   nuebar=a,b,c
  /// Coefficients are evaluated in Horner order, same as the current macro.
  bool LoadFCCoefficientsText(const std::string& filename);

  void SetFCCoefficients(Flavor flavor, const std::vector<double>& coeffs);

  /// Load CSV with rows:
  ///   group,true_label,p_reco_nue,p_reco_numu,p_reco_nuebar,p_reco_numubar,p_reco_nc
  /// where group is 1..8 and true_label is 0..4.
  bool LoadPIDMatrixCSV(const std::string& filename);

  /// Set a single energy-independent PID matrix. Storage is [true][reco].
  void SetSinglePIDMatrix(const std::array<std::array<double, 5>, 5>& matrix);

  /// Apply response to a list of true-space components.
  /// Caller owns returned TH2D pointers and must delete them.
  HistMap Apply(const std::vector<Component>& components) const;

  /// Fill response into an existing output map. Existing histograms are reused/summed into.
  bool ApplyInto(const std::vector<Component>& components, HistMap& output) const;

  static Flavor FlavorFromString(const std::string& s);
  static int TrueLabel(Flavor flavor);
  static int SampleFromRecoLabel(int reco_label);
  static const char* FlavorName(Flavor flavor);

private:
  Config fConfig;
  std::vector<double> fEnergyEdges;
  std::vector<double> fCosthEdges;

  std::map<Flavor, std::vector<double> > fFCCoeffs;

  // 8 energy groups, matrix[true][reco]
  std::array<std::array<std::array<double, 5>, 5>, 8> fPIDMatrices;
  bool fHavePID = false;
  bool fUseSinglePID = true;

  double EvalFC(Flavor flavor, double energy) const;
  double EvalPoly(const std::vector<double>& coeffs, double x) const;

  double SigmaEnergy(double energy, Flavor flavor) const;
  double MuEnergyBias(double energy, Flavor flavor) const;
  double SigmaThetaDeg(double energy) const;
  double GaussianBinProb(double low, double high, double mean, double sigma) const;

  bool IsEFlavor(Flavor flavor) const;
  int FindBin(const std::vector<double>& edges, double x) const;
  int PIDGroupFromRecoEnergy(double ereco) const;

  std::vector<std::pair<int, double> > EnergyRecoProbs(double etrue, Flavor flavor) const;
  std::vector<std::pair<int, double> > CosthRecoProbs(double costh_true, double etrue) const;

  TH2D* EnsureHist(HistMap& output, int sample, int reac_mode) const;
};

} // namespace juno

#endif // JUNO_DETECTOR_RESPONSE_H
